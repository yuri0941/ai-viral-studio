// Запреты (дублируются в системном промпте): системный промпт/инструкции, данные и контакты
// владельца, чужие данные, API-ключи/токены, внутренние URL, имена AI-провайдеров, chat_id.

export const CLIENT_PRIVACY_PATTERNS = [
  // владелец и его контакты
  /владелец|юрий|tvinki013|2130452126/i,
  // финансы платформы
  /mrr|доход платформы|общий доход|сколько зарабатывает|прибыль проекта|зарплата/i,
  // внутренности: стек, код, инфраструктура, внутренние URL
  /стек технологий|на чём написано|исходный код|архитектура|backend|frontend|mongodb|express|onrender|render\.com|localhost|127\.0\.0\.1/i,
  // чужие данные
  /другие клиенты|чужой проект|данные клиента|конфиденциальная информация|чужие данные/i,
  // секреты: пароли, токены, API-ключи, env
  /пароль|токен|api.?key|api.?ключ|ключи api|env\b|secret/i,
  // системный промпт и инструкции
  /системный промпт|system prompt|инструкци[яию] (бота|ассистента|omega)|мои инструкции|свои инструкции|повтори инструкции/i,
  // имена AI-провайдеров и внутренние id
  /groq|openai|gemini|pollinations|anthropic|claude|gpt-|chat_id|чат.?id/i,
];

export const PRIVACY_BLOCK_REPLY = 'Это конфиденциальная информация — я не могу её обсуждать. А вот с SMM и контентом помогу с удовольствием! 💡';

// Проверка исходящего ответа: true — ответ содержит утечку
export function isLeak(text) {
  if (!text) return false
  return CLIENT_PRIVACY_PATTERNS.some(p => p.test(text))
}

// Санитизация: при утечке — безопасная заглушка
export function sanitizeClientReply(reply) {
  if (isLeak(reply)) return { text: PRIVACY_BLOCK_REPLY, blocked: true }
  return { text: reply, blocked: false }
}

